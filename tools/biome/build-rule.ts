// Generates no-literal-ui-string.grit and the biome.json plugin entry from rule-config.json (SPEC §11.6).
//   bun tools/biome/build-rule.ts           write
//   bun tools/biome/build-rule.ts --check   fail if either generated output is stale
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const HERE = import.meta.dir;
const ROOT = join(HERE, "..", "..");
export const GRIT_PATH = join(HERE, "no-literal-ui-string.grit");
const BIOME_JSON = join(ROOT, "biome.json");

export interface RuleConfig {
  message: string;
  includes: string[];
  excludes: string[];
  userVisibleAttributes: string[];
  neverFlaggedAttributes: string[];
  messageFunctions: string[];
  translationFunctions: string[];
  translationProps: string[];
  properNouns: string[];
}

export function loadConfig(): RuleConfig {
  return JSON.parse(readFileSync(join(HERE, "rule-config.json"), "utf8")) as RuleConfig;
}

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\-]/g, "\\$&");
const gritString = (s: string) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

export function buildGrit(cfg: RuleConfig): string {
  const letters = 'r"(?s).*\\p{L}.*"';
  const nouns = cfg.properNouns.map(escapeRegex).join("|");
  // A literal made only of allowlisted proper nouns and non-letters is allowed.
  const allowOnly = `r"(?s)[^\\p{L}]*(?:(?:${nouns})[^\\p{L}]*)*"`;
  const msg = (id: string) => gritString(`${cfg.message} [${id}]`);
  const isText = (v: string) => `${v} <: ${letters},\n      ${v} <: not ${allowOnly}`;
  const notInTranslation = (v: string) =>
    cfg.translationFunctions.map((f) => `${v} <: not within \`${f}($...)\``).join(",\n      ");
  const attrs = cfg.userVisibleAttributes.map((a) => `\`${a}\``).join(", ");
  const templateText = (v: string) =>
    `${v} <: contains JsTemplateChunkElement() as $chunk where {\n        $chunk <: ${letters},\n        $chunk <: not ${allowOnly}\n      }`;

  const f4 = cfg.messageFunctions.map(
    (fn) => `  // F4: ${fn}(…)
  \`${fn}($m, $...)\` where {
    or {
      $m <: JsStringLiteralExpression() where { ${isText("$m").replace(/\n\s*/g, " ")} },
      $m <: JsTemplateExpression() where { ${templateText("$m").replace(/\n\s*/g, " ")} }
    },
    register_diagnostic(span=$m, message=${msg("F4")}, severity="error")
  }`,
  );

  return `// GENERATED by tools/biome/build-rule.ts from tools/biome/rule-config.json. Do not edit by hand.
// no-literal-ui-string (SPEC §11.6): user-facing text must come from the i18n catalog.
// Never flagged: attributes other than F3 (${cfg.neverFlaggedAttributes.join(", ")}),
// arguments to ${cfg.translationFunctions.map((f) => `${f}()`).join(" / ")}, and the ${cfg.translationProps.join(", ")} prop.
language js

or {
  // F1: JSX text children
  JsxText() as $text where {
    ${isText("$text")},
    register_diagnostic(span=$text, message=${msg("F1")}, severity="error")
  },
  // F2: string literals inside a JSX expression container
  JsStringLiteralExpression() as $str where {
    $str <: within JsxExpressionChild(),
    $str <: not within JsxAttribute(),
    $str <: not within JsBinaryExpression(),
    ${notInTranslation("$str")},
    ${isText("$str")},
    register_diagnostic(span=$str, message=${msg("F2")}, severity="error")
  },
  // F2: template literals inside a JSX expression container
  JsTemplateExpression() as $tpl where {
    $tpl <: within JsxExpressionChild(),
    $tpl <: not within JsxAttribute(),
    ${notInTranslation("$tpl")},
    ${templateText("$tpl")},
    register_diagnostic(span=$tpl, message=${msg("F2")}, severity="error")
  },
  // F3: literal values of user-visible attributes / props
  JsxAttribute(name=$name, initializer=JsxAttributeInitializerClause(value=$value)) where {
    $name <: or { ${attrs} },
    or {
      $value <: JsxString() as $lit where { ${isText("$lit").replace(/\n\s*/g, " ")} },
      $value <: JsxExpressionAttributeValue(expression=JsStringLiteralExpression() as $lit) where { ${isText("$lit").replace(/\n\s*/g, " ")} },
      $value <: JsxExpressionAttributeValue(expression=JsTemplateExpression() as $lit) where { ${templateText("$lit").replace(/\n\s*/g, " ")} }
    },
    register_diagnostic(span=$lit, message=${msg("F3")}, severity="error")
  },
${f4.join(",\n")},
  // F5: assigning a literal to document.title
  \`document.title = $v\` where {
    or {
      $v <: JsStringLiteralExpression() where { ${isText("$v").replace(/\n\s*/g, " ")} },
      $v <: JsTemplateExpression() where { ${templateText("$v").replace(/\n\s*/g, " ")} }
    },
    register_diagnostic(span=$v, message=${msg("F5")}, severity="error")
  }
}
`;
}

export function pluginEntry(cfg: RuleConfig) {
  return {
    path: `./${relative(ROOT, GRIT_PATH)}`,
    includes: [...cfg.includes, ...cfg.excludes.map((e) => `!${e}`)],
  };
}

function biomeJsonWithPlugin(cfg: RuleConfig): string {
  const biome = JSON.parse(readFileSync(BIOME_JSON, "utf8")) as Record<string, unknown>;
  biome.plugins = [pluginEntry(cfg)];
  return `${JSON.stringify(biome, null, 2)}\n`;
}

if (import.meta.main) {
  const cfg = loadConfig();
  const grit = buildGrit(cfg);
  const biome = biomeJsonWithPlugin(cfg);
  if (process.argv.includes("--check")) {
    const stale: string[] = [];
    if (readFileSync(GRIT_PATH, "utf8") !== grit) stale.push(relative(ROOT, GRIT_PATH));
    const current = JSON.parse(readFileSync(BIOME_JSON, "utf8")) as { plugins?: unknown };
    if (JSON.stringify(current.plugins) !== JSON.stringify([pluginEntry(cfg)])) stale.push("biome.json (plugins)");
    if (stale.length > 0) {
      console.error(`stale generated lint rule: ${stale.join(", ")}. Run: bun run lint:rule:build`);
      process.exit(1);
    }
    console.log("lint rule is up to date");
  } else {
    writeFileSync(GRIT_PATH, grit);
    writeFileSync(BIOME_JSON, biome);
    console.log(`wrote ${relative(ROOT, GRIT_PATH)} and biome.json plugins`);
  }
}
